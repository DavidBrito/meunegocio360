"""Interfaces (portas) que a camada de infraestrutura implementa (RNF-010)."""

from dataclasses import dataclass
from datetime import datetime
from typing import Protocol, Self
from uuid import UUID

from meunegocio360_core.auth.domain.models import RefreshToken, Usuario


class UsuarioRepository(Protocol):
    def get_by_email(self, email: str, *, for_update: bool = False) -> Usuario | None: ...
    def get_by_id(self, usuario_id: UUID, *, for_update: bool = False) -> Usuario | None: ...
    def add(self, usuario: Usuario) -> None: ...
    def save(self, usuario: Usuario) -> None: ...


class RefreshTokenRepository(Protocol):
    def get_by_hash(self, token_hash: str) -> RefreshToken | None: ...
    def get_by_hash_for_update(self, token_hash: str) -> RefreshToken | None: ...
    def add(self, token: RefreshToken) -> None: ...
    def save(self, token: RefreshToken) -> None: ...
    def revoke_family(self, familia_id: UUID, agora: datetime) -> None: ...
    def revoke_active_of_user(self, usuario_id: UUID, agora: datetime) -> None: ...
    def delete_older_than(self, limite: datetime) -> int: ...


class UnitOfWork(Protocol):
    usuarios: UsuarioRepository
    refresh_tokens: RefreshTokenRepository

    def __enter__(self) -> Self: ...
    def __exit__(self, exc_type: object, exc: object, tb: object) -> None: ...
    def commit(self) -> None: ...


class PasswordHasher(Protocol):
    def hash(self, senha: str) -> str: ...
    def verify(self, senha: str, senha_hash: str) -> bool: ...
    def verify_dummy(self, senha: str) -> None:
        """Gasta o mesmo tempo de uma verificacao real (anti-enumeracao, RN-03)."""


@dataclass(frozen=True, slots=True)
class IssuedAccessToken:
    token: str
    expires_in: int


class AccessTokenIssuer(Protocol):
    def issue(self, usuario: Usuario, agora: datetime) -> IssuedAccessToken: ...


@dataclass(frozen=True, slots=True)
class GeneratedRefreshToken:
    raw: str
    token_hash: str


class RefreshTokenGenerator(Protocol):
    def generate(self) -> GeneratedRefreshToken: ...
    def hash_of(self, raw: str) -> str: ...
